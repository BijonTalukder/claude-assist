import type { OptimizationPlan } from "./types.js";

export function generateProjectContext(plan: OptimizationPlan): string {
  return `# Project Context

Generated by claude-assist

## Project Overview

Language: ${plan.language}

${
  plan.isMonorepo
    ? `
## Monorepo

Tool: ${plan.monorepoTool ?? "workspace"}
Packages: ${plan.workspacePackageCount}
`
    : ""
}

## Project Structure

Important folders:

${plan.ignorableFolders.map((folder) => `- ${folder}`).join("\n")}

## Claude Usage Optimization

This file helps Claude understand the project without scanning unnecessary files.

## Recommended Context

Focus on:
- Source code changes
- Active packages
- Configuration files
- Recent modifications

Avoid:
- Dependencies
- Build output
- Generated files

`;
}

import type { Suggestion } from '@claude-assist/types';
import type { SuggestionContext, SuggestionProvider } from '../types/analysis.js';

interface LanguageRule {
  /** Folders this language commonly generates; at least one must be present. */
  folders: string[];
  label: string;
  description: string;
}

const LANGUAGE_RULES: Record<string, LanguageRule> = {
  python: {
    folders: ['venv', '.venv', '__pycache__'],
    label: 'Ignore Python caches and virtualenvs',
    description: 'venv/, __pycache__/ and similar artifacts don\'t add useful context.',
  },
  java: {
    folders: ['target'],
    label: 'Ignore Java build output',
    description: 'The target/ directory is generated bytecode — keep it out of context.',
  },
  csharp: {
    folders: ['bin', 'obj'],
    label: 'Ignore .NET build output',
    description: 'bin/ and obj/ are generated — they add noise without useful context.',
  },
  go: {
    folders: ['bin'],
    label: 'Ignore Go build output',
    description: 'The bin/ directory is compiled output that can stay out of context.',
  },
  ruby: {
    folders: ['vendor'],
    label: 'Ignore vendored gems',
    description: 'vendor/ holds dependencies, not your code.',
  },
  php: {
    folders: ['vendor'],
    label: 'Ignore PHP vendor directory',
    description: 'vendor/ holds Composer dependencies, not your code.',
  },
  rust: {
    folders: ['target'],
    label: 'Ignore Rust target directory',
    description: 'target/ is compiled output that can stay out of context.',
  },
};

function languageArtifactSuggestion(language: string, folders: string[]): Suggestion | null {
  const rule = LANGUAGE_RULES[language];
  if (!rule) return null;
  if (!rule.folders.some((folder) => folders.includes(folder))) return null;

  return {
    id: `ignore-${language}-artifacts`,
    label: rule.label,
    description: rule.description,
  };
}

/**
 * Language-specific suggestions: which generated/dependency folders to keep out
 * of context for a given language, and a tooling hint for TypeScript/JavaScript
 * projects that are still on npm/yarn. Each is gated on the analyzer actually
 * finding the folder, so nothing is suggested speculatively.
 */
export class LanguageProvider implements SuggestionProvider {
  readonly id = 'language';
  readonly priority = 10;

  getSuggestions({ analysis }: SuggestionContext): Suggestion[] {
    const suggestions: Suggestion[] = [];
    const { language, packageManager, dependencyFolders, generatedFolders } = analysis;
    const presentFolders = [...dependencyFolders, ...generatedFolders];

    const artifactSuggestion = languageArtifactSuggestion(language, presentFolders);
    if (artifactSuggestion) suggestions.push(artifactSuggestion);

    if (
      (language === 'typescript' || language === 'javascript') &&
      (packageManager === 'npm' || packageManager === 'yarn')
    ) {
      suggestions.push({
        id: 'consider-pnpm',
        label: 'Consider pnpm',
        description:
          'pnpm installs faster, saves disk with a content-addressable store, and enforces stricter dependency isolation.',
      });
    }

    return suggestions;
  }
}